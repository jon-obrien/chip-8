#define ROM_FRAMES 30

static bool run_rom(Cpu *cpu, const char *file, int frames, void (*preset)(Chip8Flags *)) {
    char path[512];
    snprintf(path, sizeof path, "%s/%s", CHIP8_ROM_DIR, file);

    Rom rom;
    if (!rom_load(path, &rom)) {
        return false;
    }

    cpu_init(cpu);
    preset(&cpu->flags);
    bool loaded = cpu_load_rom(cpu, rom.data, rom.size);
    rom_free(&rom);
    if (!loaded) {
        return false;
    }

    for (int f = 0; f < frames; f++) {
        for (int i = 0; i < CHIP8_INSTRUCTIONS_PER_CYCLE; i++) {
            cpu_step(cpu);
        }
        cpu_tick_timers(cpu);
        keypad_end_frame(cpu);
    }

    return true;
}

